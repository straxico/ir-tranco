// Helper to generate consistent monthly history from 2019-01 to 2026-09
function generateMonthlyHistory(
  baseRank2019: number,
  baseRank2026: number,
  volatility: number = 0.08,
  events: { [key: string]: number } = {} // specific multipliers for events (e.g. '2021-04': 0.6 = higher rank)
): { history: RankDataPoint[]; peakRank: number; peakDate: string } {
  const points: RankDataPoint[] = [];
  const startYear = 2019;
  const endYear = 2026;
  const totalMonths = (endYear - startYear) * 12 + 9; // up to 2026-09

  let currentRank = baseRank2019;
  let minRank = Infinity;
  let peakDate = '2019-01';

  let monthIndex = 0;
  for (let year = startYear; year <= endYear; year++) {
    const maxMonth = year === endYear ? 9 : 12;
    for (let m = 1; m <= maxMonth; m++) {
      const monthStr = m < 10 ? `0${m}` : `${m}`;
      const dateKey = `${year}-${monthStr}`;

      // Linear progress factor
      const progress = monthIndex / (totalMonths - 1);
      // Trend baseline
      const trend = baseRank2019 + (baseRank2026 - baseRank2019) * Math.pow(progress, 0.95);

      // Seasonal wave (tourism higher in summer & March/April; ecommerce higher in Nov/Dec)
      const seasonal = Math.sin((m / 12) * Math.PI * 2) * (volatility * 0.4);

      // Pseudo-random deterministic noise based on dateKey hash
      const hash = dateKey.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
      const noise = (((hash % 20) - 10) / 100) * volatility;

      // Event override
      const eventMult = events[dateKey] ?? 1.0;

      let calculated = Math.round(trend * (1 + seasonal + noise) * eventMult);
      if (calculated < 1) calculated = 1;

      if (calculated < minRank) {
        minRank = calculated;
        peakDate = dateKey;
      }

      // Generate realistic Tranco List ID
      const listId = `T${year.toString().slice(2)}${monthStr}X`;

      points.push({
        date: dateKey,
        rank: calculated,
        listId,
      });

      monthIndex++;
    }
  }

  return { history: points, peakRank: minRank, peakDate };
}

