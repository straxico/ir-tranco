// Build populated DomainItem array
export const INITIAL_DOMAINS: DomainItem[] = RAW_DOMAINS.map((cfg) => {
  const { history, peakRank, peakDate } = generateMonthlyHistory(
    cfg.baseRank2019,
    cfg.baseRank2026,
    cfg.volatility ?? 0.08,
    cfg.events ?? {}
  );

  const currentPoint = history[history.length - 1];
  const currentRank = currentPoint.rank;

  // 30 days prior (or 1 month ago)
  const prevMonthPoint = history.length >= 2 ? history[history.length - 2] : currentPoint;
  const rank30dChange = prevMonthPoint.rank - currentRank; // positive = improvement (rank value dropped)
  const rank30dAvg = Math.round((prevMonthPoint.rank + currentRank) / 2);

  // 1 year ago (12 months back)
  const oneYearBackPoint = history.length >= 13 ? history[history.length - 13] : history[0];
  const rank1yChange = oneYearBackPoint.rank - currentRank;

  // 5 years ago (60 months back)
  const fiveYearsBackPoint = history.length >= 61 ? history[history.length - 61] : history[0];
  const rank5yChange = fiveYearsBackPoint.rank - currentRank;

  const cat = CATEGORIES.find((c) => c.id === cfg.category);

  return {
    domain: cfg.domain,
    titleFa: cfg.titleFa,
    titleEn: cfg.titleEn,
    descriptionFa: cfg.descriptionFa,
    descriptionEn: cfg.descriptionEn,
    category: cfg.category,
    categoryFa: cat ? cat.nameFa : cfg.category,
    currentRank,
    rank30dAvg,
    rank30dChange,
    rank1yChange,
    rank5yChange,
    peakRank,
    peakDate,
    history,
    hosting: {
      ...cfg.hosting,
      bootmortisVerified: true,
    },
    cachedAt: new Date().toISOString(),
  };
});
